-- Satır kilidi sayesinde eşzamanlı stok giriş/çıkışlarında negatif veya ayrılmış stoğun altına düşüş olmaz.
create or replace function public.inventory_record_movement(
  p_product_id integer, p_movement_type text, p_quantity numeric,
  p_unit_cost numeric default null, p_reference text default null, p_note text default ''
) returns void
language plpgsql security definer set search_path = public as $$
declare p public.products%rowtype; next_stock numeric;
begin
  if p_movement_type not in ('receipt', 'adjustment', 'return') or p_quantity = 0 then
    raise exception 'Geçersiz stok hareketi';
  end if;
  if p_movement_type <> 'adjustment' and p_quantity < 0 then raise exception 'Giriş miktarı pozitif olmalı'; end if;
  select * into p from public.products where id = p_product_id for update;
  if not found then raise exception 'Ürün bulunamadı'; end if;
  if p.inventory_enabled <> 1 then raise exception 'Ürün için stok takibi etkin değil'; end if;
  next_stock := p.stock_on_hand + p_quantity;
  if next_stock < p.stock_reserved then raise exception 'Stok, siparişler için ayrılmış miktarın altına inemez'; end if;
  update public.products set stock_on_hand = next_stock, updated_at = now()::text where id = p_product_id;
  insert into public.inventory_movements(product_id, movement_type, quantity, unit_cost, reference, note, created_at)
  values (p_product_id, p_movement_type, p_quantity, p_unit_cost, p_reference, coalesce(p_note, ''), now()::text);
end $$;

create or replace function public.inventory_ensure_variant(p_product_id integer, p_label text) returns integer
language plpgsql security definer set search_path = public as $$
declare p public.products%rowtype; grp jsonb; part text; selected text; prefix text; groups_count integer; parts text[]; result_id integer;
begin
  select * into p from public.products where id = p_product_id;
  if not found then raise exception 'Ürün bulunamadı'; end if;
  parts := string_to_array(coalesce(p_label, ''), ' · ');
  groups_count := jsonb_array_length(coalesce(p.options_json::jsonb, '[]'::jsonb));
  if groups_count = 0 or array_length(parts, 1) <> groups_count then raise exception 'Varyasyon seçimi eksik veya geçersiz'; end if;
  for grp in select value from jsonb_array_elements(p.options_json::jsonb) loop
    prefix := grp->>'name' || ': ';
    part := null;
    select item into part from unnest(parts) as items(item) where item like (grp->>'name' || ': %') limit 1;
    if part is null then raise exception 'Varyasyon özelliği eksik: %', grp->>'name'; end if;
    selected := substring(part from length(prefix) + 1);
    if not exists (select 1 from jsonb_array_elements_text(grp->'values') as vals(value) where value = selected) then
      raise exception 'Geçersiz % seçeneği: %', grp->>'name', selected;
    end if;
  end loop;
  insert into public.inventory_variants(product_id, variant_key, label, created_at, updated_at, inventory_enabled)
    values (p_product_id, p_label, p_label, now()::text, now()::text, p.inventory_enabled)
  on conflict (product_id, variant_key) do update set active = 1, label = excluded.label, updated_at = excluded.updated_at
  returning id into result_id;
  return result_id;
end $$;

create or replace function public.inventory_record_variant_movement(
  p_variant_id integer, p_movement_type text, p_quantity numeric,
  p_unit_cost numeric default null, p_reference text default null, p_note text default ''
) returns void
language plpgsql security definer set search_path = public as $$
declare v public.inventory_variants%rowtype; p public.products%rowtype; next_stock numeric;
begin
  if p_movement_type not in ('receipt', 'adjustment', 'return') or p_quantity = 0 then raise exception 'Geçersiz stok hareketi'; end if;
  if p_movement_type <> 'adjustment' and p_quantity < 0 then raise exception 'Giriş miktarı pozitif olmalı'; end if;
  select * into v from public.inventory_variants where id = p_variant_id for update;
  if not found or v.active <> 1 then raise exception 'Ürün varyasyonu bulunamadı veya pasif'; end if;
  select * into p from public.products where id = v.product_id for update;
  if p.inventory_enabled <> 1 then raise exception 'Ürün için stok takibi etkin değil'; end if;
  if v.inventory_enabled <> 1 then raise exception 'Bu varyasyon için stok takibi etkin değil'; end if;
  next_stock := v.stock_on_hand + p_quantity;
  if next_stock < v.stock_reserved then raise exception 'Stok, siparişler için ayrılmış miktarın altına inemez'; end if;
  update public.inventory_variants set stock_on_hand = next_stock, updated_at = now()::text where id = p_variant_id;
  insert into public.inventory_movements(product_id, variant_id, variant_label, movement_type, quantity, unit_cost, reference, note, created_at)
  values (v.product_id, v.id, v.label, p_movement_type, p_quantity, p_unit_cost, p_reference, coalesce(p_note, ''), now()::text);
end $$;

-- Sipariş oluşturma/düzenleme, sevkiyat ve iptal stokla aynı DB transaction'ında yürür.
create or replace function public.sync_order_inventory() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  r record; d record; p public.products%rowtype; v public.inventory_variants%rowtype; variant_value integer;
  current_qty numeric; wanted numeric; delta numeric; current_on_hand numeric; current_reserved numeric;
  lines jsonb; order_id_value integer; order_no_value integer; order_status text;
begin
  if tg_op = 'DELETE' then
    order_id_value := old.id; order_no_value := old.order_no;
    for r in select * from public.inventory_reservations where order_id = order_id_value and state = 'reserved' for update loop
      if r.variant_id is not null then
        update public.inventory_variants set stock_reserved = greatest(0, stock_reserved - r.quantity), updated_at = now()::text where id = r.variant_id;
      else
        update public.products set stock_reserved = greatest(0, stock_reserved - r.quantity), updated_at = now()::text where id = r.product_id;
      end if;
      insert into public.inventory_movements(product_id, variant_id, variant_label, movement_type, quantity, reference, note, created_at)
      values (r.product_id, r.variant_id, r.variant_key, 'reservation_release', -r.quantity, 'Sipariş #' || order_no_value, 'Silinen siparişin stok rezervasyonu bırakıldı', now()::text);
      update public.inventory_reservations set quantity = 0, state = 'released', updated_at = now()::text where id = r.id;
    end loop;
    return old;
  end if;

  if tg_op = 'UPDATE' then
    if old.lines_json is not distinct from new.lines_json and old.status is not distinct from new.status then return new; end if;
    if old.status in ('kargoya_verildi', 'teslim_edildi') and old.lines_json is distinct from new.lines_json then
      raise exception 'Sevkiyatı yapılan siparişin ürün satırları değiştirilemez';
    end if;
  end if;
  order_id_value := new.id; order_no_value := new.order_no; order_status := new.status;
  lines := coalesce(new.lines_json::jsonb, '[]'::jsonb);

  if order_status in ('yeni', 'hazirlaniyor', 'hazirlandi') then
    for d in
      select (item->>'product_id')::integer as product_id,
             coalesce(item->>'variant', '') as variant_key,
             sum(coalesce((item->>'qty')::numeric, 0) * coalesce((item->>'units_per_package')::numeric, 1)) as quantity
      from jsonb_array_elements(lines) as entries(item)
      where coalesce(item->>'product_id', '') ~ '^[0-9]+$'
      group by (item->>'product_id')::integer, coalesce(item->>'variant', '') order by (item->>'product_id')::integer, coalesce(item->>'variant', '')
    loop
      select * into p from public.products where id = d.product_id for update;
      if not found or p.inventory_enabled <> 1 then continue; end if;
      wanted := d.quantity;
      variant_value := null;
      if jsonb_array_length(coalesce(p.options_json::jsonb, '[]'::jsonb)) > 0 then
        if d.variant_key = '' then raise exception '"%" için siparişte varyasyon seçilmelidir', p.name; end if;
        select id into variant_value from public.inventory_variants where product_id = p.id and variant_key = d.variant_key and active = 1 for update;
        if variant_value is null then raise exception '"%" · % için önce stok girişi yapılmalı', p.name, d.variant_key; end if;
        select * into v from public.inventory_variants where id = variant_value for update;
        if v.inventory_enabled <> 1 then continue; end if;
        current_on_hand := v.stock_on_hand; current_reserved := v.stock_reserved;
      else
        if d.variant_key <> '' then raise exception '"%" ürünü varyasyon kabul etmiyor', p.name; end if;
        current_on_hand := p.stock_on_hand; current_reserved := p.stock_reserved;
      end if;
      select * into r from public.inventory_reservations where order_id = order_id_value and product_id = d.product_id and variant_key = d.variant_key for update;
      current_qty := case when found and r.state = 'reserved' then r.quantity else 0 end;
      delta := wanted - current_qty;
      if delta > 0 and current_on_hand - current_reserved < delta then
        raise exception 'Yetersiz stok: % %. Kullanılabilir %, gereken ek miktar %', p.name, d.variant_key, current_on_hand - current_reserved, delta;
      end if;
      if delta <> 0 then
        if variant_value is not null then update public.inventory_variants set stock_reserved = stock_reserved + delta, updated_at = now()::text where id = variant_value;
        else update public.products set stock_reserved = stock_reserved + delta, updated_at = now()::text where id = d.product_id; end if;
        insert into public.inventory_movements(product_id, variant_id, variant_label, movement_type, quantity, reference, note, created_at)
        values (d.product_id, variant_value, nullif(d.variant_key, ''), 'order_reservation', delta, 'Sipariş #' || order_no_value, 'Sipariş stok rezervasyonu güncellendi', now()::text);
      end if;
      insert into public.inventory_reservations(order_id, product_id, variant_id, variant_key, quantity, state, updated_at)
      values (order_id_value, d.product_id, variant_value, d.variant_key, wanted, 'reserved', now()::text)
      on conflict (order_id, product_id, variant_key) do update set variant_id = excluded.variant_id, quantity = excluded.quantity, state = 'reserved', updated_at = excluded.updated_at;
    end loop;

    -- Ürün satırından kaldırılan kalemlerin ayırdığı stok bırakılır.
    for r in select * from public.inventory_reservations where order_id = order_id_value and state = 'reserved' for update loop
      if not exists (
        select 1 from jsonb_array_elements(lines) as entries(item)
        where coalesce(item->>'product_id', '') ~ '^[0-9]+$' and (item->>'product_id')::integer = r.product_id
          and coalesce(item->>'variant', '') = r.variant_key
          and (r.variant_id is null or exists (select 1 from public.inventory_variants enabled_variant where enabled_variant.id = r.variant_id and enabled_variant.inventory_enabled = 1))
      ) then
        if r.variant_id is not null then update public.inventory_variants set stock_reserved = greatest(0, stock_reserved - r.quantity), updated_at = now()::text where id = r.variant_id;
        else update public.products set stock_reserved = greatest(0, stock_reserved - r.quantity), updated_at = now()::text where id = r.product_id; end if;
        insert into public.inventory_movements(product_id, variant_id, variant_label, movement_type, quantity, reference, note, created_at)
        values (r.product_id, r.variant_id, nullif(r.variant_key, ''), 'reservation_release', -r.quantity, 'Sipariş #' || order_no_value, 'Sipariş satırı kaldırıldığı için rezervasyon bırakıldı', now()::text);
        update public.inventory_reservations set quantity = 0, state = 'released', updated_at = now()::text where id = r.id;
      end if;
    end loop;
  end if;

  if order_status in ('kargoya_verildi', 'teslim_edildi') then
    for r in select * from public.inventory_reservations where order_id = order_id_value and state = 'reserved' for update loop
      if r.variant_id is not null then
        select * into v from public.inventory_variants where id = r.variant_id for update;
        if v.stock_on_hand < r.quantity or v.stock_reserved < r.quantity then raise exception 'Varyasyon stok rezervasyonu tutarsız: %', v.label; end if;
        update public.inventory_variants set stock_on_hand = stock_on_hand - r.quantity, stock_reserved = stock_reserved - r.quantity, updated_at = now()::text where id = r.variant_id;
      else
        select * into p from public.products where id = r.product_id for update;
        if p.stock_on_hand < r.quantity or p.stock_reserved < r.quantity then raise exception 'Stok rezervasyonu tutarsız: %', p.name; end if;
        update public.products set stock_on_hand = stock_on_hand - r.quantity, stock_reserved = stock_reserved - r.quantity, updated_at = now()::text where id = r.product_id;
      end if;
      insert into public.inventory_movements(product_id, variant_id, variant_label, movement_type, quantity, reference, note, created_at)
      values (r.product_id, r.variant_id, nullif(r.variant_key, ''), 'shipment', -r.quantity, 'Sipariş #' || order_no_value, 'Sipariş kargoya verildi; stok depodan çıktı', now()::text);
      update public.inventory_reservations set state = 'consumed', updated_at = now()::text where id = r.id;
    end loop;
  elsif order_status = 'iade' then
    for r in select * from public.inventory_reservations where order_id = order_id_value and state = 'consumed' for update loop
      if r.variant_id is not null then
        update public.inventory_variants set stock_on_hand = stock_on_hand + r.quantity, updated_at = now()::text where id = r.variant_id;
      else
        update public.products set stock_on_hand = stock_on_hand + r.quantity, updated_at = now()::text where id = r.product_id;
      end if;
      insert into public.inventory_movements(product_id, variant_id, variant_label, movement_type, quantity, reference, note, created_at)
      values (r.product_id, r.variant_id, nullif(r.variant_key, ''), 'return', r.quantity, 'Sipariş #' || order_no_value, 'İade edilen siparişin ürünü depoya geri alındı', now()::text);
      update public.inventory_reservations set quantity = 0, state = 'released', updated_at = now()::text where id = r.id;
    end loop;
  elsif order_status = 'iptal' then
    for r in select * from public.inventory_reservations where order_id = order_id_value and state = 'reserved' for update loop
      if r.variant_id is not null then update public.inventory_variants set stock_reserved = greatest(0, stock_reserved - r.quantity), updated_at = now()::text where id = r.variant_id;
      else update public.products set stock_reserved = greatest(0, stock_reserved - r.quantity), updated_at = now()::text where id = r.product_id; end if;
      insert into public.inventory_movements(product_id, variant_id, variant_label, movement_type, quantity, reference, note, created_at)
      values (r.product_id, r.variant_id, nullif(r.variant_key, ''), 'reservation_release', -r.quantity, 'Sipariş #' || order_no_value, 'İptal edilen siparişin stok rezervasyonu bırakıldı', now()::text);
      update public.inventory_reservations set quantity = 0, state = 'released', updated_at = now()::text where id = r.id;
    end loop;
  end if;
  return new;
end $$;

